import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(path.resolve('.artifacts/s25-browser/package.json'));
const { chromium } = require('playwright');
const m = JSON.parse(await fs.readFile(process.argv[2], 'utf8'));
const browser = await chromium.launch({channel:'chrome', headless:true});
const context = await browser.newContext({viewport:{width:1365,height:1000}, colorScheme:'light', permissions:['clipboard-read','clipboard-write']});
await context.addInitScript(() => localStorage.setItem('sagaflow-dashboard-theme','light'));
const page = await context.newPage();
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
const shot = async name => page.screenshot({path:path.join(m.evidence,name+'.png'),fullPage:true,animations:'disabled'});
const open = async (url,id) => { await page.goto(new URL('sagaflow/instances',url).href); await page.getByRole('button',{name:new RegExp(id)}).click(); };
const invocation = () => page.getByRole('region',{name:'External invocation relationship'});
try {
  await open(m.sourceUrl,m.firstId);
  await invocation().getByText('Accepted',{exact:true}).waitFor();
  await invocation().getByText(m.firstTargetId,{exact:true}).waitFor();
  assert.match(await invocation().innerText(),/last known observation, not live remote state/);
  assert.equal(await invocation().getByRole('link').count(),0);
  assert.equal(await page.getByRole('alert').count(),0,'Normal invocation has no reconciliation warning');
  await page.getByRole('button',{name:'Copy invocation ID',exact:true}).click();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),m.invocationId);
  await shot('01-source-light');
  await page.getByRole('button',{name:'Hide external process details: InvokeRemote'}).click();
  assert.equal(await invocation().isVisible(),false);
  await page.getByRole('button',{name:'Show external process details: InvokeRemote'}).click();
  await invocation().waitFor();
  await page.getByRole('button',{name:'Switch to dark mode'}).click();
  await page.waitForFunction(()=>document.documentElement.classList.contains('dark'));
  await shot('02-source-dark');
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('aside').getBoundingClientRect().right<=1);
  await invocation().scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(()=>{const main=document.getElementById('dashboard-content');return document.documentElement.scrollWidth<=window.innerWidth && main.scrollWidth<=main.clientWidth;}),'Horizontal overflow on narrow source');
  await shot('03-source-narrow');
  await page.setViewportSize({width:1365,height:1000});
  let navigations=0; page.on('framenavigated', frame=>{if(frame===page.mainFrame()) navigations++;});
  await fs.writeFile(m.signal,'complete real RabbitMQ participant');
  await invocation().getByText('Completed',{exact:true}).first().waitFor({timeout:20000});
  assert.equal(navigations,0,'SignalR update unexpectedly navigated/reloaded');
  await shot('04-source-live-completed');
  await open(m.targetUrl,m.firstTargetId);
  const origin=page.getByRole('region',{name:'External origin'});
  await origin.getByText(m.firstId,{exact:true}).waitFor();
  assert.ok((await origin.innerText()).includes(m.sourceCorrelation));
  assert.ok((await origin.innerText()).includes(m.targetCorrelation));
  assert.notEqual(m.sourceCorrelation,m.targetCorrelation);
  assert.equal(await origin.getByRole('link').count(),0);
  await shot('05-target-origin');
  await open(m.sourceUrl,m.metadataId);
  await invocation().getByText('Not known yet',{exact:true}).waitFor();
  assert.ok((await invocation().getByText('Not recorded',{exact:true}).count())>=1);
  assert.equal(await page.getByRole('region',{name:'External origin'}).count(),0);
  assert.equal(await page.getByRole('alert').count(),0,'Missing optional metadata has no reconciliation warning');
  assert.equal(await invocation().getByRole('link').count(),0);
  assert.equal(await invocation().getByRole('button',{name:'Copy target Saga instance ID'}).count(),0);
  await shot('06-missing-metadata');
  await open(m.failedUrl,m.failedId);
  await page.getByRole('alert').getByText('Manual reconciliation required',{exact:true}).waitFor();
  assert.ok((await page.getByRole('alert').innerText()).includes('Failed'));
  await shot('07-reconciliation');
  await page.setViewportSize({width:390,height:844});
  await page.waitForFunction(()=>document.querySelector('aside').getBoundingClientRect().right<=1);
  await page.getByRole('alert').scrollIntoViewIfNeeded();
  assert.ok(await page.evaluate(()=>{const main=document.getElementById('dashboard-content');return document.documentElement.scrollWidth<=window.innerWidth && main.scrollWidth<=main.clientWidth;}),'Horizontal overflow on narrow reconciliation');
  await shot('08-reconciliation-narrow');
  await page.setViewportSize({width:1365,height:1000});
  await page.goto(new URL('sagaflow/workflows',m.sourceUrl).href);
  await page.getByRole('button',{name:/^local /}).click();
  await page.locator('[data-workflow-kind="step"]').first().click();
  await page.getByRole('dialog',{name:'Step details'}).waitFor();
  await shot('09-workflow-drawer');
  await page.getByRole('button',{name:'Close node details'}).click();
  assert.equal(await page.getByRole('dialog',{name:'Step details'}).count(),0);
  assert.deepEqual(errors,[],'Browser page errors');
  await fs.writeFile(path.join(m.evidence,'browser-result.json'),JSON.stringify({status:'PASS',engine:'Chrome/Chromium via Playwright',browserVersion:browser.version(),checks:['source','target','correlation','reconciliation','last-known','null metadata','expand-collapse','workflow drawer','clipboard','light-dark','390px','SignalR without reload'],errors},null,2));
  console.log('BROWSER_UX_PASS');
} catch(error) { await shot('failure'); console.error(error); process.exitCode=1; }
finally { await browser.close(); }
